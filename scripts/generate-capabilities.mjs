import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const manifestPath = resolve(root, 'capabilities/manifest.json')
const manifest = JSON.parse(await readFile(manifestPath, 'utf8'))
const check = process.argv.includes('--check')

function assert(condition, message) {
  if (!condition) throw new Error(`Capability manifest: ${message}`)
}

assert(manifest.schema_version === 1, 'unsupported schema_version')
assert(/^\d+\.\d+\.\d+$/.test(manifest.spec_version), 'spec_version must be semver')
const ids = new Set()
const tools = new Set()
for (const capability of manifest.capabilities) {
  assert(/^[a-z][a-z0-9_]*$/.test(capability.id), `invalid id ${capability.id}`)
  assert(!ids.has(capability.id), `duplicate id ${capability.id}`)
  ids.add(capability.id)
  assert(capability.examples?.length >= 2, `${capability.id} needs at least two examples`)
  assert(capability.use_when && capability.do_not_use_when, `${capability.id} needs semantic guidance`)
  assert(capability.introduced && capability.updated, `${capability.id} needs version metadata`)
  for (const tool of capability.tools) {
    assert(!tools.has(tool), `tool ${tool} is assigned more than once`)
    tools.add(tool)
  }
}
for (const provider of manifest.providers) {
  for (const id of provider.agent_capabilities) {
    assert(ids.has(id), `${provider.id} references unknown agent capability ${id}`)
  }
}

const banner = '// Generated by scripts/generate-capabilities.mjs. Do not edit.\n'
const json = JSON.stringify(manifest, null, 2)
const capabilityIds = manifest.capabilities.map(capability => capability.id)
const protocolCapabilities = [...new Set(manifest.providers.flatMap(provider => provider.protocol_capabilities))].sort()

const outputs = new Map()
outputs.set(
  'packages/provider-sdk/src/capabilities.generated.ts',
  `${banner}export type Capability = ${protocolCapabilities.map(value => JSON.stringify(value)).join(' | ')};\n\nexport const PROVIDER_CAPABILITIES = ${JSON.stringify(protocolCapabilities, null, 2)} as const;\n`,
)

const mcpEntries = Object.fromEntries(manifest.capabilities.flatMap(capability =>
  capability.tools.map(tool => [tool, {
    capability: capability.id,
    description: `${capability.summary} Use when ${capability.use_when} Do not use when ${capability.do_not_use_when}`,
  }]),
))
outputs.set(
  'packages/mcp/src/capabilities.generated.ts',
  `${banner}export const TOOL_GUIDANCE = ${JSON.stringify(mcpEntries, null, 2)} as const;\n\nexport type EconomicCapability = ${capabilityIds.map(value => JSON.stringify(value)).join(' | ')};\n`,
)

outputs.set(
  'web/src/lib/capabilities.generated.ts',
  `${banner}export const CAPABILITY_MANIFEST = ${json} as const;\n\nexport type CapabilityManifestEntry = typeof CAPABILITY_MANIFEST.capabilities[number];\n`,
)

outputs.set(
  'rust/mandate-core/src/capabilities_generated.rs',
  `// Generated by scripts/generate-capabilities.mjs. Do not edit.\n` +
  `pub const CAPABILITY_MANIFEST_JSON: &str = r#\"${json}\"#;\n` +
  `pub const CAPABILITY_IDS: &[&str] = &[\n${capabilityIds.map(value => `    ${JSON.stringify(value)},`).join('\n')}\n];\n`,
)

const docs = `# Mandate capability reference

Capability Spec ${manifest.spec_version} · Updated ${manifest.updated_at}

Mandate capabilities are organized by what an operator asks an agent to accomplish. Run \`mandate capabilities --json\` or use \`list_capabilities\` to inspect what is executable for the current economic account.

${manifest.capabilities.map(capability => `## ${capability.title}

\`${capability.id}\` · ${capability.intent_group} · ${capability.mutation ? 'Mutation' : 'Read only'}

${capability.description}

**Try saying**
${capability.examples.map(example => `- “${example}”`).join('\n')}

**Use when:** ${capability.use_when}

**Do not use when:** ${capability.do_not_use_when}

**Requires:** ${capability.requires_provider_categories.length ? capability.requires_provider_categories.join(', ') + ' provider' : 'No provider route'}

**Effect:** ${capability.side_effect}

Introduced in Mandate ${capability.introduced} · Updated ${capability.updated}
`).join('\n')}
`
outputs.set('docs/CAPABILITIES.md', docs)

const skill = `---
name: mandate-economic-account
description: Use the locally installed Mandate CLI for balances, receiving, invoicing, payments, transfers, refunds, and transaction history.
metadata:
  requires:
    bins:
      - mandate
---

# Mandate economic operations

Use the Mandate CLI for every economic operation. Always pass \`--json\` and consume returned JSON rather than terminal prose.

- Run \`mandate whoami --json\` first to discover the scoped economic account, authority, and grant.
- Run \`mandate capabilities --json\` when availability is uncertain. Treat it as current account truth; do not infer availability from this skill.
- Supply a stable \`--idempotency-key\` for every mutation and reuse it when retrying.
- Never invoke \`mandate admin\` or provider-management commands.
- Never print, persist, summarize, or place temporary card credentials in notes, memory, logs, or messages.
- Treat \`available\`, \`reserved\`, \`pending\`, and \`settled\` as distinct states.
- Do not describe value held at one provider as spendable through another rail unless Mandate reports that capability.

## Semantic capability guidance

${manifest.capabilities.map(capability => `### ${capability.id}
Use when ${capability.use_when}
Do not use when ${capability.do_not_use_when}
`).join('\n')}
Run \`mandate status --json\` if the daemon appears unavailable and report the machine-readable error unchanged.
`
outputs.set('integrations/openclaw/SKILL.md', skill)

const includedTools = ['whoami', 'list_capabilities', ...manifest.capabilities.flatMap(capability => capability.tools)]
const hermes = `# Generated by scripts/generate-capabilities.mjs. Do not edit.\n` +
`mcp_servers:\n  mandate:\n    command: mandate-mcp\n    args: []\n    enabled: true\n    supports_parallel_tool_calls: false\n    tools:\n      include:\n${includedTools.map(tool => `        - ${tool}`).join('\n')}\n`
outputs.set('integrations/hermes/mandate.yaml', hermes)

let drifted = false
for (const [relativePath, content] of outputs) {
  const path = resolve(root, relativePath)
  let current = ''
  try {
    current = await readFile(path, 'utf8')
  } catch {}
  if (current === content) continue
  if (check) {
    console.error(`${relativePath} is out of date`)
    drifted = true
  } else {
    await writeFile(path, content)
    console.log(`generated ${relativePath}`)
  }
}

if (drifted) process.exitCode = 1
